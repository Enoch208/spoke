import type { ClientInput, ClientMethod } from "./methods";

export type HttpVerb = "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
export type RouteAuth = "public" | "session";

export type LiveRoute = {
  verb: HttpVerb;
  path: string;
  auth: RouteAuth;
  payload?: string;
  multipart?: boolean;
  idempotencyField?: string;
};

type Options = Omit<LiveRoute, "verb" | "path" | "auth">;

const make =
  (auth: RouteAuth) =>
  (verb: HttpVerb, path: string, options: Options = {}): LiveRoute => ({
    verb,
    path,
    auth,
    ...options,
  });

