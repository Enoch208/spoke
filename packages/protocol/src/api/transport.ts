const campaignVaultPath = "/merchant/campaigns/:campaignId/vault";

export const routeFor = <M extends ClientMethod>(method: M, input: ClientInput<M>): LiveRoute => {
  const route: LiveRoute = clientRoutes[method];
  if (method === "vault.get" && "campaignId" in input && input.campaignId !== undefined) {
    return { ...route, path: campaignVaultPath };
  }
  return route;
};

export const isReadMethod = (method: ClientMethod) => clientRoutes[method].verb === "GET";
